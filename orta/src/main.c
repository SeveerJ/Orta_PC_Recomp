static void set_default_env(const char *name, const char *value)
{
    if (!getenv(name)) {
        _putenv_s(name, value);
        SetEnvironmentVariableA(name, value);
    }
}

static void trim(char *s)
{
    char *e;
    while (*s == ' ' || *s == '\t')
        memmove(s, s + 1, strlen(s));
    e = s + strlen(s);
    while (e > s && (e[-1] == ' ' || e[-1] == '\t' || e[-1] == '\r' || e[-1] == '\n'))
        *--e = 0;
}

static void apply_setting(const char *section, const char *key, const char *val)
{
    char buf[64];
    if (!_stricmp(section, "Advanced")) {
        set_default_env(key, val);
        return;
    }
    if (!_stricmp(key, "Resolution")) {
        /* 720/1080/1440/2160/Native: the smallest whole multiple of 480
         * lines that covers it (see launcher.h). */
        snprintf(buf, sizeof buf, "%d", orta_res_scale(val));
        set_default_env("RECOMP_GPU_SCALE", buf);
        set_default_env("RECOMP_RES_CHOICE", val);
    } else if (!_stricmp(key, "RenderScale")) {
        set_default_env("RECOMP_GPU_SCALE", val);
    } else if (!_stricmp(key, "Widescreen")) {
        set_default_env("RECOMP_WIDESCREEN", atoi(val) ? "1" : "0");
    } else if (!_stricmp(key, "CropX")) {
        set_default_env("RECOMP_CROP_X", val);
    } else if (!_stricmp(key, "CropY")) {
        set_default_env("RECOMP_CROP_Y", val);
    } else if (!_stricmp(key, "Fullscreen")) {
        set_default_env("RECOMP_FULLSCREEN", atoi(val) ? "1" : "0");
    } else if (!_stricmp(key, "WindowHeight")) {
        set_default_env("RECOMP_WINDOW_HEIGHT", val);
    } else if (!_stricmp(key, "FrameRateCap")) {
        set_default_env("RECOMP_FPS_CAP", val);
    } else if (!_stricmp(key, "VSync")) {
        set_default_env("RECOMP_VSYNC", atoi(val) ? "1" : "0");
    } else if (!_stricmp(key, "Volume")) {
        int v = atoi(val);
        if (v < 0) v = 0;
        if (v > 100) v = 100;
        snprintf(buf, sizeof buf, "%.2f", v / 100.0);
        set_default_env("RECOMP_APU_GAIN", buf);
    } else if (!_stricmp(key, "SfxVolume")) {
        int v = atoi(val);
        if (v < 0) v = 0;
        if (v > 100) v = 100;
        snprintf(buf, sizeof buf, "%.2f", v / 100.0);
        set_default_env("RECOMP_APU_SFX", buf);
    } else if (!_stricmp(key, "Rumble")) {
        set_default_env("RECOMP_RUMBLE", atoi(val) ? "1" : "0");
    } else if (!_stricmp(key, "RumbleStrength")) {
        set_default_env("RECOMP_RUMBLE_STRENGTH", val);
    }
}

static void load_ini(const char *path, int create)
{
    char line[512], section[64] = "";
    FILE *f = fopen(path, "rb");
    if (!f) {
        if (!create)
            return;
        f = fopen(path, "wb");
        if (f) {
            fputs(k_settings_default, f);
            fclose(f);
        }
        f = fopen(path, "rb");
        if (!f)
            return;
    }
    while (fgets(line, sizeof line, f)) {
        char *eq, *sc;
        trim(line);
        if (!line[0] || line[0] == ';' || line[0] == '#')
            continue;
        if (line[0] == '[') {
            char *e = strchr(line, ']');
            if (e) *e = 0;
            snprintf(section, sizeof section, "%s", line + 1);
            continue;
        }
        eq = strchr(line, '=');
        if (!eq)
            continue;
        *eq = 0;
        sc = strchr(eq + 1, ';');               /* trailing comment */
        if (sc && _stricmp(section, "Advanced"))
            *sc = 0;
        trim(line);
        trim(eq + 1);
        if (line[0])
            apply_setting(section, line, eq + 1);
    }
    fclose(f);
}

/* Where the game's files are: a game_files folder next to the .exe when
 * there is one (a packaged copy), else the developer's tree. */
static char g_game_dir[MAX_PATH] = YOUR_GAME_DIR;
static char g_xbe_path[MAX_PATH] = YOUR_GAME_XBE_PATH;

static void find_game_dir(void)
{
    char dir[MAX_PATH], xbe[MAX_PATH], *slash;
    DWORD n = GetModuleFileNameA(NULL, dir, MAX_PATH);
    if (!n || n >= MAX_PATH)
        return;
    slash = strrchr(dir, '\\');
    if (slash)
        slash[0] = 0;
    snprintf(xbe, sizeof xbe, "%s\\game_files\\default.xbe", dir);
    if (GetFileAttributesA(xbe) != INVALID_FILE_ATTRIBUTES) {
        snprintf(g_game_dir, sizeof g_game_dir, "%s\\game_files", dir);
        snprintf(g_xbe_path, sizeof g_xbe_path, "%s", xbe);
    }
}

/* settings.ini (the player's) first, then engine.ini (a release build's
 * runtime switches, all [Advanced]); whichever sets a variable first wins. */
static void load_settings(void)
{
    char dir[MAX_PATH], path[MAX_PATH], *slash;
    DWORD n = GetModuleFileNameA(NULL, dir, MAX_PATH);
    if (!n || n >= MAX_PATH)
        return;
    slash = strrchr(dir, '\\');
    if (slash)
        slash[1] = 0;
    snprintf(path, sizeof path, "%ssettings.ini", dir);
    {   /* write the defaults first, so the launcher has a file to edit */
        FILE *f = fopen(path, "rb");
        if (f) fclose(f);
        else if ((f = fopen(path, "wb")) != NULL) { fputs(k_settings_default, f); fclose(f); }
    }
    if (!launcher_maybe_run(path))
        ExitProcess(0);
    load_ini(path, 1);
    snprintf(path, sizeof path, "%sengine.ini", dir);
    load_ini(path, 0);
}

